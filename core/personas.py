def get_persona(name: str) -> dict[str, str]:
    return PERSONAS.get(name, PERSONAS["computer"])


def wrap_untrusted(content: str, source: str) -> str:
    """Обёртка недоверенного контента. Экраним закрывающий тег, чтобы нельзя было 'выйти'."""
    safe = content.replace("</data>", "<\/data>")[:60000]
    return f"<data source=\"{source}\">\n{safe}\n</data>"
